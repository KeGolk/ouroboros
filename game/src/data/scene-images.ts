/** Get all images for a specific chapter */
export function getChapterImages(chapter: number): SceneImage[] {
  return sceneImages.filter((img) => img.chapter === chapter);
}

/** Get all images of a specific category */
export function getImagesByCategory(category: SceneImage['category']): SceneImage[] {
  return sceneImages.filter((img) => img.category === category);
}

/** Get a specific image by ID */
export function getSceneImage(id: string): SceneImage | undefined {
  return sceneImages.find((img) => img.id === id);
}

/** Get all title card images */
export function getTitleCards(): SceneImage[] {
  return sceneImages.filter((img) => img.category === 'title_card');
}

/** Get all transition images */
export function getTransitions(): SceneImage[] {
  return sceneImages.filter((img) => img.category === 'transition');
}

/** Get all ending images */
export function getEndingImages(): SceneImage[] {
  return sceneImages.filter((img) => img.category === 'ending');
}

/** Get all UI assets */
export function getUIAssets(): SceneImage[] {
  return sceneImages.filter((img) => img.category === 'ui');
}

/** Get all combat scene images */
export function getCombatImages(): SceneImage[] {
  return sceneImages.filter((img) => img.category === 'combat');
}

