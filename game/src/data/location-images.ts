/** All location/environment images in the game */
export const LOCATION_IMAGES: LocationImage[] = [
  ...factionHQImages,
  ...chapterSettingImages,
  ...worldLocationImages,
  ...regionPanoramaImages,
  ...transitionImages,
  ...endingImages,
  ...additionalLocationImages,
];

/** Total count of location images */
export const LOCATION_IMAGE_COUNT = LOCATION_IMAGES.length;

// ─── Lookup Helpers ─────────────────────────────────────────────────────────────

/** Get a location image by ID */
export function getLocationImage(id: string): LocationImage | undefined {
  return LOCATION_IMAGES.find((img) => img.id === id);
}

/** Get all images for a specific chapter */
export function getImagesForChapter(chapter: number): LocationImage[] {
  return LOCATION_IMAGES.filter((img) => img.chapters.includes(chapter));
}

/** Get all images for a specific faction */
export function getImagesForFaction(factionId: string): LocationImage[] {
  return LOCATION_IMAGES.filter((img) => img.faction === factionId);
}

/** Get all images for a specific category */
export function getImagesByCategory(category: ImageCategory): LocationImage[] {
  return LOCATION_IMAGES.filter((img) => img.category === category);
}

/** Get all images associated with a map location */
export function getImagesForLocation(locationId: string): LocationImage[] {
  return LOCATION_IMAGES.filter((img) => img.locationId === locationId);
}

/** Get all images matching a tag */
export function getImagesByTag(tag: string): LocationImage[] {
  return LOCATION_IMAGES.filter((img) => img.tags.includes(tag));
}

/** Get a CSS placeholder gradient for a location image */
export function getPlaceholderStyle(id: string): string {
  const img = getLocationImage(id);
  return img?.placeholderColor ?? 'linear-gradient(135deg, #1a1a1a 0%, #2a2a2a 100%)';
}

/**
 * Image statistics for verification
 */
export function getImageStats() {
  const stats = {
    total: LOCATION_IMAGES.length,
    byCategory: {} as Record<string, number>,
    byFaction: {} as Record<string, number>,
    byChapter: {} as Record<number, number>,
    withLocationId: LOCATION_IMAGES.filter((img) => img.locationId).length,
  };

  for (const img of LOCATION_IMAGES) {
    stats.byCategory[img.category] = (stats.byCategory[img.category] || 0) + 1;
    if (img.faction) {
      stats.byFaction[img.faction] = (stats.byFaction[img.faction] || 0) + 1;
    }
    for (const ch of img.chapters) {
      stats.byChapter[ch] = (stats.byChapter[ch] || 0) + 1;
    }
  }

  return stats;
}
